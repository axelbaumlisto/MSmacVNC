#include "RFBKeySym.h"

#include <assert.h>
#include <stddef.h>
#include <stdint.h>

int main(void)
{
    static const uint16_t lower[32] = {
        0x044e, 0x0430, 0x0431, 0x0446, 0x0434, 0x0435, 0x0444, 0x0433,
        0x0445, 0x0438, 0x0439, 0x043a, 0x043b, 0x043c, 0x043d, 0x043e,
        0x043f, 0x044f, 0x0440, 0x0441, 0x0442, 0x0443, 0x0436, 0x0432,
        0x044c, 0x044b, 0x0437, 0x0448, 0x044d, 0x0449, 0x0447, 0x044a
    };
    static const uint16_t upper[32] = {
        0x042e, 0x0410, 0x0411, 0x0426, 0x0414, 0x0415, 0x0424, 0x0413,
        0x0425, 0x0418, 0x0419, 0x041a, 0x041b, 0x041c, 0x041d, 0x041e,
        0x041f, 0x042f, 0x0420, 0x0421, 0x0422, 0x0423, 0x0416, 0x0412,
        0x042c, 0x042b, 0x0417, 0x0428, 0x042d, 0x0429, 0x0427, 0x042a
    };

    for (size_t i = 0; i < 32; ++i) {
        assert(macVNCUnicodeForRFBKeySym(0x06c0U + (uint32_t)i) == lower[i]);
        assert(macVNCUnicodeForRFBKeySym(0x06e0U + (uint32_t)i) == upper[i]);
    }
    assert(macVNCUnicodeForRFBKeySym(0x06a3U) == 0x0451U);
    assert(macVNCUnicodeForRFBKeySym(0x06b3U) == 0x0401U);
    assert(macVNCUnicodeForRFBKeySym(0x0100044fU) == 0x044fU);
    assert(macVNCUnicodeForRFBKeySym('A') == 'A');
    assert(macVNCUnicodeForRFBKeySym(0x0101f600U) == 0U); /* non-BMP unsupported */
    return 0;
}
